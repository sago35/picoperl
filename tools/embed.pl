#!/usr/bin/perl
# Embeds Perl source files into a C file as string literals so the firmware can
# run them (the first file is the main script, the rest are require()-able).
#
#   perl tools/embed.pl -o pp_scripts.c -b lib scripts/main.pl lib/PicoPerl/*.pm
use strict;
use warnings;

sub norm { my $p = shift; $p =~ s{\\}{/}g; 1 while $p =~ s{[^/.][^/]*/\.\.(/|$)}{}; $p =~ s{/+$}{}; return $p }

my ($out, $base, $root, @files);
while (@ARGV) {
    my $a = shift @ARGV;
    if ($a eq '-o') { $out = shift @ARGV; next }
    if ($a eq '-b') { $base = norm(shift @ARGV); $base =~ s{/+$}{}; next }   # files under -b DIR land in lib/ with their relative path
    if ($a eq '-r') { $root = norm(shift @ARGV); $root =~ s{/+$}{}; next }   # other files under -r DIR keep their DIR-relative path
    push @files, $a;
}
die "usage: embed.pl -o OUT.c [-b LIBDIR] [-r ROOTDIR] FILE.pl...\n" unless $out && @files;

open my $fh, '>', $out or die "cannot write $out: $!";
print $fh "/* generated by tools/embed.pl - do not edit */\n";
print $fh "struct pp_embedded_file { const char *name; const char *src; };\n\n";

my @entries;
for my $i (0 .. $#files) {
    my $path = $files[$i];
    open my $in, '<', $path or die "cannot read $path: $!";
    local $/; my $src = <$in>; close $in;
    $src =~ s/\r\n/\n/g;
    my $norm = norm($path);
    # the stored name is the path on the drive; the first file is always /main.pl
    my $name;
    if ($i == 0) { $name = 'main.pl' }
    elsif (defined $base && index($norm, "$base/") == 0) { $name = 'lib/' . substr($norm, length($base) + 1) }
    elsif (defined $root && index($norm, "$root/") == 0) { $name = substr($norm, length($root) + 1) }
    else { ($name = $norm) =~ s{.*/}{} }
    print $fh "static const char pp_src_$i\[\] =\n";
    for my $line (split /(?<=\n)/, $src) {
        my $esc = '';
        for my $ch (split //, $line) {
            my $o = ord $ch;
            if ($ch eq '\\')      { $esc .= '\\\\' }
            elsif ($ch eq '"')    { $esc .= '\\"' }
            elsif ($ch eq "\n")   { $esc .= '\\n' }
            elsif ($ch eq "\t")   { $esc .= '\\t' }
            elsif ($o < 32 || $o == 127 || $o > 126) { $esc .= sprintf('\\%03o', $o) }
            else                  { $esc .= $ch }
        }
        print $fh "    \"$esc\"\n";
    }
    print $fh "    ;\n\n";
    push @entries, "    { \"$name\", pp_src_$i },";
}

print $fh "const struct pp_embedded_file pp_embedded_files[] = {\n", join("\n", @entries), "\n};\n";
print $fh "const int pp_embedded_count = ", scalar(@files), ";\n";
close $fh;
print "embedded ", scalar(@files), " file(s) into $out\n";
