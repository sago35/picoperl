/*
 * picoperl firmware entry point for the Raspberry Pi Pico (RP2040).
 *
 * Boots, mounts the flash filesystem (exposed to the host as a USB drive),
 * brings up TinyUSB (CDC console + HID keyboard + MSC) and runs /main.pl.
 * Modules are loaded with `use`/`require` from /lib on the drive; the files
 * embedded at build time are used to populate a fresh drive and as a
 * fallback when a file is not on the drive. When the host writes to the
 * drive the interpreter is restarted (USB stays connected).
 *
 * The interpreter runs on its own 64 KiB stack allocated from the heap: the
 * SDK's default stack lives in the 8 KiB scratch area at the top of RAM and
 * is not protected from a growing heap.
 */
