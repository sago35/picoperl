/* ---- WS2812B / SK6812 LEDs on a PIO state machine (pico-examples ws2812.pio, pre-assembled) ---- */
static const uint16_t ws2812_program_instructions[] = {
    0x6221, /* 0: out x, 1  side 0 [2] */
    0x1123, /* 1: jmp !x, 3 side 1 [1] */
    0x1400, /* 2: jmp 0     side 1 [4] */
    0xa442, /* 3: nop       side 0 [4] */
};
static const struct pio_program ws2812_program = { .instructions = ws2812_program_instructions, .length = 4, .origin = -1 };

typedef struct { PIO pio; uint sm; uint pin; bool used; } ws_strip;
static ws_strip strips[4];
static int ws2812_offset = -1;

static int ws2812_setup(uint pin) {
    int h = -1;
    for (int i = 0; i < 4; i++) { if (strips[i].used && strips[i].pin == pin) return i; if (!strips[i].used && h < 0) h = i; }
    if (h < 0) return -1;
    PIO pio = pio0;
    if (ws2812_offset < 0) ws2812_offset = pio_add_program(pio, &ws2812_program);
    int sm = pio_claim_unused_sm(pio, false);
    if (sm < 0) return -1;
    pio_gpio_init(pio, pin);
    pio_sm_set_consecutive_pindirs(pio, (uint)sm, pin, 1, true);
    pio_sm_config c = pio_get_default_sm_config();
    sm_config_set_wrap(&c, (uint)ws2812_offset, (uint)ws2812_offset + 3);
    sm_config_set_sideset(&c, 1, false, false);
    sm_config_set_sideset_pins(&c, pin);
    sm_config_set_out_shift(&c, false, true, 24);        /* 24 bits per LED, MSB first: G R B */
    sm_config_set_fifo_join(&c, PIO_FIFO_JOIN_TX);
    float div = (float)clock_get_hz(clk_sys) / (800000.0f * 10);   /* T1+T2+T3 = 10 cycles per bit */
    sm_config_set_clkdiv(&c, div);
    pio_sm_init(pio, (uint)sm, (uint)ws2812_offset, &c);
    pio_sm_set_enabled(pio, (uint)sm, true);
    strips[h] = (ws_strip){ pio, (uint)sm, pin, true };
    return h;
}
static void ws2812_send(ws_strip *s, const uint32_t *words, int n) {
    for (int i = 0; i < n; i++) pio_sm_put_blocking(s->pio, s->sm, words[i]);
    while (!pio_sm_is_tx_fifo_empty(s->pio, s->sm)) tight_loop_contents();
    sleep_us(30 + 80);   /* last word + reset latch */
}
static ws_strip *strip_arg(pp_interp *I, pp_list *a) {
    int h = a->n ? (int)pp_to_int(a->v[0]) : -1;
    if (h < 0 || h >= 4 || !strips[h].used) { pp_die(I, "ws2812: bad handle (call ws2812_init(pin) first)"); return NULL; }
    return &strips[h];
}
/* ws2812_init($pin) -> handle */
NATIVE(n_ws2812_init) {
    UNUSED;
    int h = ws2812_setup((uint)ARG_INT(0, 16));
    if (h < 0) return pp_die(I, "ws2812_init: no free PIO state machine");
    return pp_int(h);
}
/* ws2812_write_raw($h, @grb) : 32-bit words, 0xGGRRBBxx (top 24 bits are sent), one per LED */
NATIVE(n_ws2812_write_raw) {
    UNUSED;
    ws_strip *s = strip_arg(I, a); if (!s) return pp_undef();
    int n = a->n - 1;
    uint32_t words[64];
    if (n > 64) n = 64;
    for (int i = 0; i < n; i++) words[i] = (uint32_t)pp_to_int(a->v[1 + i]);
    ws2812_send(s, words, n);
    return pp_int(n);
}
/* ws2812_put_color($h, { R => r, G => g, B => b }) or ($h, $r, $g, $b): one LED */
NATIVE(n_ws2812_put_color) {
    UNUSED;
    ws_strip *s = strip_arg(I, a); if (!s) return pp_undef();
    int r = 0, g = 0, b = 0;
    if (a->n >= 2 && a->v[1].t == PP_REF && a->v[1].u.o->kind == PP_OHASH) {
        pp_obj *h = a->v[1].u.o;
        r = (int)pp_to_int(pp_hash_get(h, "R", 1)); g = (int)pp_to_int(pp_hash_get(h, "G", 1)); b = (int)pp_to_int(pp_hash_get(h, "B", 1));
    } else if (a->n >= 2 && pp_val_is_array_ref(a->v[1])) {
        pp_obj *arr = a->v[1].u.o;
        r = (int)pp_to_int(pp_array_get(arr, 0)); g = (int)pp_to_int(pp_array_get(arr, 1)); b = (int)pp_to_int(pp_array_get(arr, 2));
    } else { r = ARG_INT(1, 0); g = ARG_INT(2, 0); b = ARG_INT(3, 0); }
    uint32_t w = ((uint32_t)(g & 0xFF) << 24) | ((uint32_t)(r & 0xFF) << 16) | ((uint32_t)(b & 0xFF) << 8);
    ws2812_send(s, &w, 1);
    return pp_int(1);
}

/* ---- ADC: GPIO26-29 (channels 0-3), plus channel 4 = on-chip temperature sensor ---- */
static bool adc_inited;
static int adc_channel_of(int pin) {
    if (pin >= 26 && pin <= 29) return pin - 26;
    if (pin == 4) return 4;             /* temperature sensor (Adc::TEMPERATURE) */
    return -1;
}
/* Adc::_configure($pin) -> 1, or undef for a pin without ADC */
NATIVE(n_adc_configure) {
    UNUSED;
    int pin = ARG_INT(0, -1), ch = adc_channel_of(pin);
    if (ch < 0) return pp_undef();
    if (!adc_inited) { adc_init(); adc_inited = true; }
    if (ch == 4) adc_set_temp_sensor_enabled(true); else adc_gpio_init((uint)pin);
    return pp_int(1);
}
/* Adc::_read($pin) -> raw 12-bit sample (0..4095) */
NATIVE(n_adc_read) {
    UNUSED;
    int ch = adc_channel_of(ARG_INT(0, -1));
    if (ch < 0 || !adc_inited) return pp_undef();
    adc_select_input((uint)ch);
    return pp_int(adc_read());
}

