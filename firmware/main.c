#include <malloc.h>
extern char __StackLimit;   /* end of RAM usable by the heap (linker) */
static long heap_free_bytes(void) {
    /* bytes malloc could still hand out: unused RAM above the heap top + free blocks inside it */
    struct mallinfo mi = mallinfo();
    char *top = (char *)sbrk(0);
    long unused = (long)(&__StackLimit - top);
    if (unused < 0) unused = 0;
    return unused + (long)mi.fordblks;
}
