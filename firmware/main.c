void pp_host_poll(void) {
    tud_task();
    tud_cdc_write_flush();
    flashfs_poll();
    if (current && flashfs_reload_pending()) pp_request_exit(current, PP_EXIT_RELOAD);
}

void pp_host_write(int fd, const char *buf, int len) {
    (void)fd;
    fwrite(buf, 1, len, stdout);   /* UART mirror (pico stdio) */
    fflush(stdout);
    if (!tud_cdc_connected()) return;
    /* write to the CDC port; give up after a short while so a host that is not
       reading cannot stall the keyboard */
    absolute_time_t deadline = make_timeout_time_ms(20);
    int off = 0;
    while (off < len) {
        uint32_t n = tud_cdc_write(buf + off, (uint32_t)(len - off));
        off += (int)n;
        tud_cdc_write_flush();
        tud_task();
        if (n == 0 && time_reached(deadline)) break;
    }
}

int pp_host_const(const char *name, pp_val *out) { return pp_keycodes_const(name, out); }

void pp_host_fatal(const char *msg) {
    pp_host_write(2, msg, (int)strlen(msg));
    pp_host_write(2, "picoperl: rebooting\n", 20);
    sleep_ms(100);
    watchdog_reboot(0, 0, 10);
    for (;;) tight_loop_contents();
}

static char *embedded_file(const char *name) {
    const char *base = strrchr(name, '/');
    base = base ? base + 1 : name;
    for (int i = 0; i < pp_embedded_count; i++) {
        const char *n = pp_embedded_files[i].name;
        if (strcmp(n, name) == 0 || strcmp(n, base) == 0) {
            size_t len = strlen(pp_embedded_files[i].src);
            char *copy = malloc(len + 1);
            if (!copy) return NULL;
            memcpy(copy, pp_embedded_files[i].src, len + 1);
            return copy;
        }
    }
    return NULL;
}

/* @INC on the board: /lib and / on the drive, then the files built into the firmware */
char *pp_host_read_file(const char *name) {
    char *s = flashfs_find_file(name);
    if (s) return s;
    return embedded_file(name);
}

uint32_t pp_host_millis(void) { return to_ms_since_boot(get_absolute_time()); }
int64_t pp_host_time(void) { return (int64_t)(to_us_since_boot(get_absolute_time()) / 1000000); }

void pp_host_sleep_ms(uint32_t ms) {
    absolute_time_t deadline = make_timeout_time_ms(ms);
    do {
        pp_host_poll();
        if (time_reached(deadline)) break;
        if (current && current->ctl) break;     /* exit/reload requested: return to the interpreter */
        sleep_us(200);
    } while (1);
}

char *pp_host_read_line(void) {
    /* blocking read of one line from the CDC console. Enter may arrive as CR, LF or CR LF;
       typed characters are echoed so plain terminals show what is being typed. */
    static bool last_was_cr;
    char buf[256]; int n = 0;
    for (;;) {
        pp_host_poll();
        if (current && current->ctl) break;
        if (!tud_cdc_available()) { sleep_us(200); continue; }
        int c = tud_cdc_read_char();
        if (c < 0) continue;
        if (c == '\n' && last_was_cr && n == 0) { last_was_cr = false; continue; }   /* LF of a CR LF pair */
        last_was_cr = (c == '\r');
        if (c == '\r' || c == '\n') { tud_cdc_write_str("\r\n"); tud_cdc_write_flush(); buf[n++] = '\n'; break; }
        if (c == 8 || c == 127) { if (n > 0) { n--; tud_cdc_write_str("\b \b"); tud_cdc_write_flush(); } continue; }
        if (n < (int)sizeof buf - 2) { buf[n++] = (char)c; tud_cdc_write_char((char)c); tud_cdc_write_flush(); }
    }
    buf[n] = 0;
    char *r = malloc(n + 1);
    if (r) memcpy(r, buf, n + 1);
    return r;
}

